"""Local, screenshot-only review UI. No model-generated HTML is served to the reviewer."""
from __future__ import annotations

import argparse
import json
import mimetypes
import secrets
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

from . import evaluate, package as P, review
from .render import Renderer

WEB = Path(__file__).parent / 'web' / 'review.html'


def make_server(dataset, host='127.0.0.1', port=8765, runs=None):
    dataset = Path(dataset).resolve()
    items = {p.name: p for p in sorted(dataset.iterdir()) if p.is_dir() and review.image_path(p)}
    if not items:
        raise ValueError('검수할 문서가 없습니다')
    token, viewed = secrets.token_urlsafe(32), {}
    cache = dataset / '.review-cache'
    candidates = {}
    if runs:
        for model in sorted(Path(runs).resolve().iterdir()):
            if model.is_dir():
                for key in items:
                    for stage, sub in [('최초', 'round0'), ('최종', 'final')]:
                        path = model / key / sub
                        if path.is_dir():
                            candidates[(key, model.name + '/' + stage)] = path

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def send(self, body, status=200, mime='application/json; charset=utf-8'):
            data = json.dumps(body, ensure_ascii=False).encode() if not isinstance(body, bytes) else body
            self.send_response(status)
            self.send_header('Content-Type', mime)
            self.send_header('Content-Length', str(len(data)))
            self.send_header('Cache-Control', 'no-store')
            self.send_header('X-Content-Type-Options', 'nosniff')
            self.send_header('Content-Security-Policy', "default-src 'self'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src 'self'; connect-src 'self'; frame-ancestors 'none'")
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            url = urlparse(self.path)
            if url.path == '/':
                return self.send(WEB.read_bytes().replace(b'__TOKEN__', token.encode()), mime='text/html; charset=utf-8')
            if url.path == '/api/items':
                return self.send([{'id': key, 'review': review.status(p),
                                   'candidates': [label for k, label in candidates if k == key]} for key, p in items.items()])
            query = parse_qs(url.query)
            key = query.get('id', [''])[0]
            if key not in items:
                return self.send({'error': '문서를 찾을 수 없습니다'}, 404)
            item = items[key]
            try:
                if url.path == '/api/item':
                    path = item / 'contract.json'
                    contract = review.load_contract(item) if path.exists() else review.draft(item)
                    return self.send({'id': key, 'contract': contract, 'review': review.status(item)})
                if url.path == '/image':
                    name = query.get('name', ['original'])[0]
                    if name == 'original':
                        path = review.image_path(item)
                    else:
                        # Serve only PNGs generated by this session, never arbitrary filesystem paths.
                        path = cache / key / name
                        if path.suffix != '.png' or path.name != name or not path.is_file():
                            return self.send({'error': '미리보기가 없습니다'}, 404)
                    return self.send(path.read_bytes(), mime=mimetypes.guess_type(path.name)[0] or 'image/png')
                return self.send({'error': '찾을 수 없습니다'}, 404)
            except (ValueError, OSError, KeyError, TypeError) as e:
                return self.send({'error': str(e)}, 400)

        def do_POST(self):
            if self.headers.get('X-Review-Token') != token:
                return self.send({'error': '잘못된 검수 세션'}, 403)
            try:
                length = int(self.headers.get('Content-Length', 0))
                if not 0 < length <= 2_000_000:
                    raise ValueError('요청 크기 오류')
                body = json.loads(self.rfile.read(length))
                key = body['id']
                if key not in items:
                    raise ValueError('문서를 찾을 수 없습니다')
                item = items[key]
                if self.path == '/api/preview':
                    contract = review.validate(body['contract'])
                    pkg = P.load(item / 'reference')
                    if pkg['issues']:
                        raise ValueError(', '.join(pkg['issues']))
                    if set(evaluate.entries(contract['schema'])) != set(evaluate.entries(pkg['schema'])):
                        raise ValueError('기준 필드 변경은 reference/schema.json과 template.html에도 반영하세요')
                    review.write_json(item / 'contract.json', contract)
                    expected = review.fingerprint(item)
                    output = cache / key
                    output.mkdir(parents=True, exist_ok=True)
                    images = []
                    with Renderer() as renderer:
                        for case in [{'name': 'sample', 'data': contract['sample']}] + contract['cases']:
                            name = case['name']
                            shot = renderer.render(P.html(pkg, case['data']), output / f'{name}.png')
                            if not shot['width'] or not shot['height']:
                                raise ValueError(name + ': 렌더링 실패')
                            images.append({'name': name, 'image': name + '.png', 'problems': shot['problems'], 'data': case['data']})
                    if review.fingerprint(item) != expected:
                        raise ValueError('렌더링 중 파일이 변경되었습니다. 다시 시도하세요')
                    viewed[key] = expected
                    return self.send({'fingerprint': expected, 'images': images, 'review': review.status(item)})
                if self.path == '/api/candidate':
                    label = body['candidate']
                    if (key, label) not in candidates:
                        raise ValueError('모델 결과가 없습니다')
                    path = candidates[(key, label)]
                    contract = review.load_contract(item)
                    case = next(c for c in [{'name': 'sample', 'data': contract['sample']}] + contract['cases'] if c['name'] == body['case'])
                    pkg = P.load(path)
                    if pkg['issues']:
                        raise ValueError(', '.join(pkg['issues']))
                    mp = path.parent / 'field_map.json'
                    mapping, tables = evaluate.align(contract['schema'], pkg['schema'], json.loads(mp.read_text()) if mp.exists() else None)
                    values = pkg['sample'] if case['name'] == 'sample' else evaluate.translate(case['data'], pkg, mapping, tables)
                    output = cache / key / 'candidate.png'
                    with Renderer() as renderer:
                        shot = renderer.render(P.html(pkg, values), output)
                    if not shot['width']:
                        raise ValueError('모델 결과 렌더링 실패')
                    return self.send({'image': 'candidate.png', 'problems': shot['problems'], 'mapping': mapping,
                                      'unmapped': sorted(set(evaluate.entries(contract['schema'])) - set(mapping))})
                if self.path == '/api/decision':
                    if viewed.get(key) != body.get('fingerprint'):
                        raise ValueError('먼저 기준 미리보기를 생성해 확인하세요')
                    return self.send(review.decide(item, body['decision'], body.get('reviewer', ''), body.get('checks', {}),
                                                   body.get('note', ''), body['fingerprint']))
                return self.send({'error': '찾을 수 없습니다'}, 404)
            except Exception as e:
                return self.send({'error': str(e)}, 400)

    return HTTPServer((host, port), Handler)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('dataset', nargs='?', default='evalset/v1')
    ap.add_argument('--port', type=int, default=8765)
    ap.add_argument('--runs', help='모델 결과를 나란히 볼 bench 출력 폴더')
    a = ap.parse_args(argv)
    server = make_server(a.dataset, port=a.port, runs=a.runs)
    print(f'검수 뷰어: http://127.0.0.1:{server.server_port} (Ctrl+C 종료)', flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
